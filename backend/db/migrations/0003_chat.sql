-- +goose Up

-- Foreign keys inside a schema, and to identity.users, are composite on
-- (workspace_id, id): a row can never point at another tenant's row, even for
-- a role that bypasses RLS. Links to other domains are typed references with
-- no constraint.

CREATE SCHEMA chat;

CREATE TABLE chat.channels (
    id           uuid PRIMARY KEY,
    workspace_id uuid NOT NULL REFERENCES identity.workspaces (id),
    name         text NOT NULL,
    kind         text NOT NULL CHECK (kind IN ('public', 'private')),
    -- Bumped by UPDATE ... RETURNING in the message transaction: the channel's
    -- gapless, commit-ordered sequence.
    last_seq     bigint NOT NULL DEFAULT 0,
    created_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, id)
);

CREATE TABLE chat.channel_members (
    channel_id   uuid NOT NULL,
    user_id      uuid NOT NULL,
    workspace_id uuid NOT NULL,
    role         text NOT NULL DEFAULT 'member' CHECK (role IN ('member', 'owner')),
    joined_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (channel_id, user_id),
    FOREIGN KEY (workspace_id, channel_id) REFERENCES chat.channels (workspace_id, id) ON DELETE CASCADE,
    FOREIGN KEY (workspace_id, user_id) REFERENCES identity.users (workspace_id, id) ON DELETE CASCADE
);

-- "Which channels is this user in" (MemberChannelIDs) reads by user.
CREATE INDEX channel_members_user_idx ON chat.channel_members (workspace_id, user_id);

CREATE TABLE chat.messages (
    id            uuid PRIMARY KEY, -- UUIDv7, generated by the application
    workspace_id  uuid NOT NULL,
    channel_id    uuid NOT NULL,
    seq           bigint NOT NULL,
    author_kind   text NOT NULL CHECK (author_kind IN ('user', 'agent')),
    author_id     uuid NOT NULL, -- a user, or authz.AgentID(name) for an agent
    body          text NOT NULL,
    mentions      jsonb NOT NULL DEFAULT '[]',
    -- Denormalised FileRef snapshots: chat never reads the files schema.
    attachments   jsonb NOT NULL DEFAULT '[]',
    -- protojson of chat.v1.Artifact; only ready slips are stored.
    artifact      jsonb,
    client_msg_id text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    -- The (channel_id, seq) index also serves "seq < before ORDER BY seq DESC".
    UNIQUE (channel_id, seq),
    UNIQUE (author_id, client_msg_id),
    FOREIGN KEY (workspace_id, channel_id) REFERENCES chat.channels (workspace_id, id) ON DELETE CASCADE
);
